def schemas():
    """Collect every published JSON schema definition, rejecting incompatible duplicates."""
    definitions = {}
    roots = {}
    for name, model in (
        ("EvidenceRequest", EvidenceRequest), ("EvidenceResponse", EvidenceResponse),
        ("CapabilityRegistry", CapabilityRegistry), ("SimulationScenario", SimulationScenario),
        ("ErrorResponse", ErrorResponse),
        ("SubmitRequest", SubmitRequest), ("VariantRequest", VariantRequest),
        ("IncidentInvestigationRequest", investigation_contracts.IncidentInvestigationRequest),
        ("IncidentInvestigationResponse", investigation_contracts.IncidentInvestigationResponse),
    ):
        schema = TypeAdapter(model).json_schema(ref_template="#/components/schemas/{model}")
        for key, definition in schema.pop("$defs", {}).items():
            if key in definitions and definitions[key] != definition:
                raise ValueError(f"Incompatible schema definitions: {key}")
            definitions[key] = definition
        roots[name] = schema
    definitions.update(roots)
    for name in ("SessionRequest", "SessionResponse", "SessionPatch", "IncidentRequest", "IncidentResponse",
                 "PrepareRequest", "DraftResponse", "RunResponse", "CancelRequest", "TurnRequest",
                 "SimulationOutput", "UiAction", "LocationReceipt", "StatusRequest", "InvestigationRequest"):
        module = investigation_contracts if name == "InvestigationRequest" else contracts
        schema = getattr(module, name).model_json_schema(ref_template="#/components/schemas/{model}")
        definitions.update(schema.pop("$defs", {}))
        definitions[name] = schema
    return definitions


def ts_type(schema):
    """Render one JSON schema as a TypeScript type expression."""
    if not schema:
        return "unknown"
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "anyOf" in schema or "oneOf" in schema:
        return " | ".join(f"({ts_type(s)})" for s in schema.get("anyOf", schema.get("oneOf")))
    kind = schema.get("type")
    if kind == "null":
        return "null"
    if kind in ("integer", "number"):
        return "number"
    if kind in ("string", "boolean"):
        return kind
    if kind == "array":
        return f"Array<{ts_type(schema['items'])}>"
    if kind == "object" or "properties" in schema:
        required = schema.get("required", [])
        fields = [f'{json.dumps(name)}{"" if name in required else "?"}: {ts_type(value)};'
                  for name, value in schema.get("properties", {}).items()]
        additional = schema.get("additionalProperties")
        if isinstance(additional, dict):
            fields.append(f"[key: string]: {ts_type(additional)};")
        elif additional is True:
            fields.append("[key: string]: unknown;")
        return "{ " + " ".join(fields) + " }"
    raise ValueError(f"Unhandled TypeScript schema: {schema}")


def evacuation_ref(ref):
    """Point a component reference at its Evacuation_-prefixed definition in schemas/api-schema.yaml."""
    return "#/components/schemas/Evacuation_" + ref.rsplit("/", 1)[-1]


def rewrite_refs(value):
    """Prefix references and discriminator mapping targets so generated definitions cannot collide with AG-UI schemas."""
    if isinstance(value, list):
        return [rewrite_refs(v) for v in value]
    if isinstance(value, dict):
        rewritten = {k: (evacuation_ref(v) if k == "$ref" else rewrite_refs(v)) for k, v in value.items()}
        discriminator = rewritten.get("discriminator")
        if isinstance(discriminator, dict) and isinstance(discriminator.get("mapping"), dict):
            # A mapping target is a reference too; unprefixed, it names a component that does not exist.
            discriminator["mapping"] = {tag: evacuation_ref(ref) for tag, ref in discriminator["mapping"].items()}
        return rewritten
    return value


def agent_inputs(definitions):
    """Project API schemas into agent tool inputs, excluding fields the broker supplies."""
    def expand(value):
        if isinstance(value, list):
            return [expand(v) for v in value]
        if isinstance(value, dict):
            if "$ref" in value:
                return expand(definitions[value["$ref"].rsplit("/", 1)[-1]])
            return {k: expand(v) for k, v in value.items() if k not in ("title", "discriminator")}
        return value

    result = {}
    for name, model, bound in (
        ("prepare_simulation", "PrepareRequest", {"request_id", "session_id", "incident_id", "location_revision"}),
        ("submit_simulation", "SubmitRequest", {"request_id", "capability_version"}),
        ("get_simulation_status", "StatusRequest", set()),
        ("get_simulation_evidence", "EvidenceRequest", set()),
        ("create_simulation_variant", "VariantRequest", {"request_id", "capability_version"}),
    ):
        payload = expand(definitions[model])
        if bound:
            payload["properties"] = {k: v for k, v in payload["properties"].items() if k not in bound}
            payload["required"] = [k for k in payload.get("required", []) if k not in bound]
        result[name] = {"type": "object", "additionalProperties": False,
                        "properties": {"payload": payload}, "required": ["payload"]}
    return json.dumps(result, indent=2, sort_keys=True) + "\n"


def api_schema(definitions, source):
    """Replace the generated block in schemas/api-schema.yaml and type simulationData."""
    if START in source:
        before, tail = source.split(START, 1)
        _, after = tail.split(END, 1)
        source = before + after.lstrip("\n")
    generic = """        simulationData:
          type: object
          nullable: true
          description: Authoritative simulation output attached by the authenticated Lab broker.
          additionalProperties: true"""
    typed = """        simulationData:
          $ref: "#/components/schemas/Evacuation_SimulationOutput"
          nullable: true"""
    source = source.replace(generic, typed)
    if "        simulationData:" not in source:
        index = source.index("      properties:", source.index("    UniversalContent:")) + len("      properties:")
        source = source[:index] + "\n" + typed + source[index:]
    block = START + "\n"
    block += "".join(f"    Evacuation_{name}: {json.dumps(rewrite_refs(value), sort_keys=True)}\n"
                     for name, value in sorted(definitions.items()))
    block += END + "\n"
    # The source ends within components.schemas; each generated definition stays at that level.
    return source.rstrip() + "\n\n" + block


def fire_exposure_contracts():
    """Publish the same pure models to the browser, private service and AG-UI schema."""
    definitions = {}
    for model in (AssessmentResult, ExposureAssessmentRequest, LandscapeAssessmentRequest,
                  FireRiskJobReference, FireRiskJobResponse, FireRiskPreparationError, FireRiskRetryRequest):
        value = model.model_json_schema(ref_template="#/components/schemas/{model}")
        definitions.update(value.pop("$defs", {}))
        definitions[model.__name__] = value
    return definitions


def fire_schema(definitions, source):
    if FIRE_START in source:
        before, tail = source.split(FIRE_START, 1)
        _, after = tail.split(FIRE_END, 1)
        source = before + after.lstrip("\n")
    if "        fireExposureData:" not in source:
        index = source.index("      properties:", source.index("    UniversalContent:")) + len("      properties:")
        source = source[:index] + """
        fireExposureData:
          type: array
          default: []
          description: Source-bound fire exposure assessments attached by the authenticated API broker.
          items:
            $ref: "#/components/schemas/FireExposure_AssessmentResult" """ .rstrip() + source[index:]
    if "        fireExposureJobs:" not in source:
        index = source.index("      properties:", source.index("    UniversalContent:")) + len("      properties:")
        source = source[:index] + """
        fireExposureJobs:
          type: array
          default: []
          description: Owned durable landscape preparation jobs attached only by the authenticated API broker.
          items:
            $ref: "#/components/schemas/FireExposure_FireRiskJobReference" """.rstrip() + source[index:]
    if "        fireExposureError:" not in source:
        index = source.index("      properties:", source.index("    UniversalContent:")) + len("      properties:")
        source = source[:index] + """
        fireExposureError:
          description: Safe terrain preparation handoff failure attached only by the authenticated API broker.
          $ref: "#/components/schemas/FireExposure_FireRiskPreparationError" """.rstrip() + source[index:]

    def prefix(value):
        if isinstance(value, list):
            return [prefix(item) for item in value]
        if isinstance(value, dict):
            return {key: (item.replace("#/components/schemas/", "#/components/schemas/FireExposure_")
                          if key == "$ref" else prefix(item)) for key, item in value.items()}
        if isinstance(value, str) and value.startswith("#/components/schemas/"):
            return value.replace("#/components/schemas/", "#/components/schemas/FireExposure_")
        return value
    block = FIRE_START + "\n"
    block += "".join(f"    FireExposure_{name}: {json.dumps(prefix(value), sort_keys=True)}\n"
                     for name, value in sorted(definitions.items()))
    return source.rstrip() + "\n\n" + block + FIRE_END + "\n"


def outputs():
    """Return {path: expected text} for every generated contract consumer."""
    definitions = schemas()

    def ref(name):
        return {"$ref": f"#/components/schemas/{name}"}

    def schema_only_owner():
        """Stand in for demo_access.workspace_owner, which reads the demo-session cookie; never serves."""
        raise RuntimeError("Schema-only dependency must never serve a request")

    # No lifespan, access settings, production store, or provider clients are initialized.
    app = FastAPI(title="Evacuation & Crew Access", version="1", description=GENERATED)
    app.include_router(create_config_router())
    app.include_router(create_router(schema_only_owner))
    app.include_router(create_investigation_router(schema_only_owner))
    app.include_router(create_fire_exposure_router(schema_only_owner))
    app.include_router(create_broker_router(schema_only_owner))
    app.include_router(create_demo_router())
    app.include_router(create_radio_router(schema_only_owner))
    app.include_router(create_incident_investigation_router(schema_only_owner, InvestigationReaders(
        context=service.context, owned_job=simulation_jobs.owned_job,
        build_evidence=evidence.build_evidence, planning_summary=evidence.planning_summary)))
    openapi = app.openapi()
    # Include canonical schemas that are also used by Gateway wrappers.
    for name, schema in definitions.items():
        openapi["components"]["schemas"].setdefault(name, schema)
    # There is no user sign-in: every owner-scoped operation uses the anonymous demo-session cookie.
    openapi["components"]["securitySchemes"] = {
        "demoSession": {"type": "apiKey", "in": "cookie", "name": "__Host-wildfire-demo"}}
    for path, operations in openapi["paths"].items():
        if path not in ("/api/v1/capabilities", "/api/v1/workspace-config", "/api/v1/demo/session"):
            for operation in operations.values():
                operation["security"] = [{"demoSession": []}]
    typescript = "// " + GENERATED + "\n"
    typescript += "".join(f"export type {name} = {ts_type(schema)};\n"
                          for name, schema in sorted(definitions.items()))
    # Preserve references as a bundle; the Gateway adapter will add only its hidden trusted context.
    public_tools = {
        "description": GENERATED,
        "tools": [{"name": "get_simulation_evidence",
                   "description": "Read bounded simulation evidence. Follow pagination before comparing outcomes.",
                   "input_schema": ref("EvidenceRequest"), "output_schema": ref("EvidenceResponse")},
                  *[{"name": name, "description": description, "input_schema": ref(input_model),
                     "output_schema": ref(output_model)}
                    for name, description, input_model, output_model in (
                        ("prepare_simulation", "Prepare current-input scenario; does not start a job.",
                         "PrepareRequest", "DraftResponse"),
                        ("submit_simulation", "Submit a reviewed draft once.", "SubmitRequest", "RunResponse"),
                        ("get_simulation_status", "Read the selected run status and progress.",
                         "StatusRequest", "RunResponse"),
                        ("create_simulation_variant", "Prepare a controlled frozen-input variant.",
                         "VariantRequest", "DraftResponse"),
                    )]],
        "components": {"schemas": definitions},
    }

    def pretty(value):
        return json.dumps(value, indent=2, sort_keys=True, ensure_ascii=False) + "\n"

    fire_definitions = fire_exposure_contracts()
    fire_types = "// " + GENERATED + "\n" + "".join(
        f"export type {name} = {ts_type(schema)};\n" for name, schema in sorted(fire_definitions.items()))
    fire_openapi = {
        "openapi": "3.1.0", "info": {"title": "Private Fire Exposure Modeler", "version": "1"},
        "paths": {"/v1/exposure/assessments": {"post": {
            "security": [{"serviceKey": []}],
            "requestBody": {"required": True, "content": {"application/json": {
                "schema": ref("ExposureAssessmentRequest")}}},
            "responses": {"200": {"description": "Completed illustrative assessment", "content": {
                "application/json": {"schema": ref("AssessmentResult")}}}},
        }}},
        "components": {"schemas": fire_definitions, "securitySchemes": {
            "serviceKey": {"type": "http", "scheme": "bearer"}}},
    }
    fire_openapi["paths"]["/v1/landscape/assessments"] = {"post": {
        "security": [{"serviceKey": []}],
        "requestBody": {"required": True, "content": {"application/json": {
            "schema": ref("LandscapeAssessmentRequest")}}},
        "responses": {"200": {"description": "Completed terrain and fuel scenario or typed failure", "content": {
            "application/json": {"schema": ref("AssessmentResult")}}}},
    }}
    return {
        CONTRACTS / "openapi.json": pretty(openapi),
        CONTRACTS / "public-tools.json": pretty(public_tools),
        CONTRACTS / "capabilities.json": pretty(capabilities().model_dump(mode="json")),
        ROOT / "ui/src/features/evacuation/generated/contracts.ts": typescript,
        ROOT / "backend/runtime/agents/simulation_agent/tool-inputs.json": agent_inputs(definitions),
        ROOT / "schemas/fire-exposure/openapi.json": pretty(fire_openapi),
        ROOT / "ui/src/features/fire-exposure/generated/contracts.ts": fire_types,
        API_SCHEMA: fire_schema(fire_definitions, api_schema(definitions, API_SCHEMA.read_text())),
    }


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="Fail on drift instead of writing files")
    args = parser.parse_args(argv)
    drift = []
    for path, content in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                drift.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if drift:
        print("Generated contract drift (run without --check): " + ", ".join(drift), file=sys.stderr)
        return 1
    print("Integration contracts verified." if args.check else "Integration contracts exported.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
